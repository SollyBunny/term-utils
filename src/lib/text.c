static void drawGlyph(int x, int y, const Glyph *img) {
	int px = 0;
	int py = 0;
	bool black = true;

	for (int i = 0; i < 128; i++) {
		uint8_t n = img->d[i];

		if (n == 255)
			break;

		if (n == 254) {
			px = 0;
			py++;
			black = true;
			continue;
		}

		if (black && n > 0) {
			printf("\033[%d;%dH", y + py, x + px);

			for (int j = 0; j < n; j++)
				putchar(' ');
		}

		px += n;
		black = !black;
	}
}

void drawText(int x, int y, const char *string, bool center) {
	int width = 0;
	int height = 0;

	for (const char *p = string; *p; p++) {
		if (*p == ' ') {
			width += 2;
		} else {
			const Glyph *glyph = &FONT_DATA[(uint8_t)*p];
			width += glyph->x;
			if (glyph->y > height)
				height = glyph->y;
		}
	}

	if (center) {
		x -= width / 2;
		y -= height / 2;
	}

	int cursor = x;

	for (const char *p = string; *p; p++) {
		if (*p == ' ') {
			cursor += 3;
			continue;
		}

		const Glyph *glyph = &FONT_DATA[(uint8_t)*p];

		drawGlyph(cursor, y, glyph);

		cursor += glyph->x + 1; // 1 pixel gap
	}

	fflush(stdout);
}
